let x = 16.75;

let roundValue = Math.round(x);
let square = Math.sqrt(x);
let power = Math.pow(x, 3);
let randomNumber = Math.floor(Math.random() * 41) + 10;

console.log(`Original Number: ${x}`);
console.log(`Rounded Value: ${roundValue}`);
console.log(`Square Root: ${square}`);
console.log(`Power (x^3): ${power}`);
console.log(`Random Number (10-50): ${randomNumber}`);
